# Konstanta offset untuk Kelvin
KELVIN_OFFSET = 273.15

# Input suhu Celsius
celsius = float(input("Masukkan suhu (°C): "))

# Konversi ke Fahrenheit dan Kelvin
fahrenheit = (9 / 5) * celsius + 32
kelvin = celsius + KELVIN_OFFSET

# Tampilkan hasil dengan dua angka desimal
print(f"\nSuhu dalam Celsius    : {celsius:.2f} °C")
print(f"Suhu dalam Fahrenheit : {fahrenheit:.2f} °F")
print(f"Suhu dalam Kelvin     : {kelvin:.2f} K")


